"""Устаревший скрипт для docxtpl.

Раньше этот файл вставлял в рабочий шаблон теги ``{%tr ... %}``. Текущий
генератор использует python-docx и такой шаблон только испортит. Скрипт
оставлен как заглушка, чтобы случайный запуск не изменил файл шаблона.
"""


def fix_template():
    raise SystemExit(
        "fix_template.py отключён: шаблон Шаблоны/Шаблон_ТТН.docx "
        "предназначен для python-docx. Изменения не внесены."
    )


if __name__ == "__main__":
    fix_template()
